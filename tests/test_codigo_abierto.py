def test_dedup_exacta_y_aproximada_persistente(tmp_path):
    d = Dedup(tmp_path / "v.sqlite")
    assert d.check(PY_OK)[0] is None
    _, sha, sig = d.check(PY_OK)
    d.add(sha, sig)
    d.commit()
    assert d.check(PY_OK + "   \n")[0] == "duplicado"                    # espacios finales no cuentan
    casi = PY_OK.replace("return self.temp >= 60", "return self.temp >= 65")
    assert d.check(casi)[0] == "casi_duplicado"
    otro = "\n".join(f"def f{i}(x):\n    return x * {i} + {i * i}  # paso {i}" for i in range(40))
    assert d.check(otro)[0] is None
    d2 = Dedup(tmp_path / "v.sqlite")                                       # persiste entre corridas
    assert d2.check(PY_OK)[0] == "duplicado"
    # Contra el corpus existente (train.bin con encabezado ⟦repo⟧), de forma incremental.
    corp = tmp_path / "repos_codigo"
    corp.mkdir()
    (corp / "train.bin").write_bytes(f"⟦repo: mio⟧ ⟦archivo: a.py⟧\n{otro}".encode() + b"\x00")
    assert d2.index_existing([corp]) == 1 and d2.index_existing([corp]) == 0
    assert d2.check(otro)[0] == "duplicado"
    # Por tramos: muchos documentos y uno más largo que el tramo (se saltea sin trabarse).
    d3 = Dedup(tmp_path / "v3.sqlite")
    docs = [f"def g{i}(x):\n    return x + {i}  # {'n' * (i % 7)}\n" for i in range(50)]
    big = tmp_path / "big"
    big.mkdir()
    (big / "train.bin").write_bytes(b"\x00".join(x.encode() for x in docs[:20] + ["#" * 5000] + docs[20:]) + b"\x00")
    assert d3.index_existing([big], chunk=1000) == 50
    assert d3.check(docs[42])[0] == "duplicado"


def _pipe(tmp_path, cfg=None):
    w = CorpusWriter(tmp_path / "out", apply_rules=False, near_dup=None, min_chars=0)
    return Pipeline(cfg or {}, w, Dedup(tmp_path / "v.sqlite")), w


