def _bins(folder: Path) -> bytes:
    return b"".join((folder / n).read_bytes() for n in ("train.bin", "val.bin") if (folder / n).exists())


def _git_repo(path: Path) -> Path:
    path.mkdir(parents=True)
    run = lambda *a: subprocess.run(["git", "-C", str(path), *a], check=True, capture_output=True)  # noqa: E731
    run("init", "-q")
    run("config", "user.email", "dev@example.com")
    run("config", "user.name", "Dev")
    (path / "LICENSE").write_text("MIT License\n\nPermission is hereby granted, free of charge, to any person\n")
    (path / "temp.py").write_text(PY_OK)
    run("add", ".")
    run("commit", "-qm", "control de temperatura")
    (path / "temp.py").write_text(PY_OK.replace("return self.temp >= 60",
                                                "if self.temp is None:\n            return False\n"
                                                "        return self.temp >= 60  # aviso: ana@correo.com"))
    run("commit", "-qam", "fix: la cama sin sensor colgaba el firmware")
    (path / "ia.py").write_text(PY_OK.replace("Cama", "CamaIA"))
    run("add", ".")
    run("commit", "-qm", "fix: helper\n\nCo-Authored-By: Claude <noreply@anthropic.com>")
    (path / "README.md").write_text("# Cama\n")
    run("add", ".")
    run("commit", "-qm", "documentación")
    return path


