class FakeClient:
    def __init__(self, routes: dict, files: dict | None = None):
        self.routes, self.files, self.seen = routes, files or {}, []
        self.settings = SimpleNamespace(min_interval=0)

    def get(self, url, *, purpose="", respect_robots=True, headers=None, **kw):
        self.seen.append((url, dict(headers or {})))
        for key, body in self.routes.items():
            if key in url:
                return SimpleNamespace(text=body if isinstance(body, str) else json.dumps(body))
        from hope.tools.web import WebError
        raise WebError(f"HTTP 404 en {url}")

    def download(self, url, dest, *, purpose="", max_bytes=0, headers=None, respect_robots=True):
        self.seen.append((url, dict(headers or {})))
        dest = Path(dest)
        dest.parent.mkdir(parents=True, exist_ok=True)
        data = next(v for k, v in self.files.items() if url.endswith(k))
        dest.write_bytes(data)
        return {"completo": True, "bytes": len(data), "total": len(data)}

    def authorize_page(self, url, purpose, respect_robots=True):
        self.seen.append((url, {}))
        return url, "github.com"


def _parquet(rows: list[dict]) -> bytes:
    pa = pytest.importorskip("pyarrow")
    pq = pytest.importorskip("pyarrow.parquet")
    buf = io.BytesIO()
    pq.write_table(pa.Table.from_pylist(rows), buf)
    return buf.getvalue()


