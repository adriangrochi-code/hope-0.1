def test_licencias_permisivas_por_defecto_y_copyleft_activable():
    assert spdx("mit") == "MIT" and spdx("apache-2.0") == "Apache-2.0" and spdx("GPL-3.0-or-later") == "GPL-3.0"
    assert spdx("NOASSERTION") is None and spdx("") is None
    p = LicensePolicy()
    for ok in ("MIT", "apache-2.0", "BSD-3-Clause", "isc", "Unlicense", "CC0-1.0", "Zlib", "MIT OR GPL-3.0",
               ["mit", "bsd-2-clause"]):
        assert p.allows(ok), ok
    for bad in ("GPL-3.0", "AGPL-3.0", "LGPL-2.1", "MPL-2.0", "MIT AND GPL-2.0", None, "", [], ["MIT", "GPL-3.0"],
                "propietaria"):
        assert not p.allows(bad), bad
    assert LicensePolicy({"incluir_mpl": True}).allows("MPL-2.0")
    assert LicensePolicy({"incluir_copyleft": True}).allows("GPL-3.0") and not LicensePolicy().allows("GPL-3.0")
    # El encabezado SPDX del archivo manda sobre la licencia del repo.
    assert file_license("// SPDX-License-Identifier: GPL-2.0-only\nint x;", ["MIT"]) == "GPL-2.0-only"
    assert not p.allows(file_license("# SPDX-License-Identifier: GPL-2.0-only\n", ["MIT"]))
    assert file_license("x = 1", ["mit", "MIT"]) == "MIT" and file_license("x", []) is None
    assert detect_license_text("MIT License\n\nPermission is hereby granted, free of charge, to any person") == "MIT"
    assert detect_license_text("Apache License\nVersion 2.0, January 2004") == "Apache-2.0"
    assert detect_license_text("GNU GENERAL PUBLIC LICENSE\nVersion 3, 29 June 2007") == "GPL-3.0"
    assert detect_license_text("Redistribution and use in source and binary forms ... Neither the name") == "BSD-3-Clause"


